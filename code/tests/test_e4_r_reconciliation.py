from __future__ import annotations

import csv
import ast
import json
from pathlib import Path

import pytest


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/non_jev/v2/e4_v1_1/e4_r_reconciliation"
E43 = ROOT / "results/non_jev/v2/e4_v1_1/e4_3_operating_regimes"


def jsonl(path: Path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def test_e4_r_scripts_are_cpu_offline_only():
    tree = ast.parse((ROOT / "scripts/e4_r_reconciliation.py").read_text(encoding="utf-8"))
    imports = [node for node in ast.walk(tree) if isinstance(node, (ast.Import, ast.ImportFrom))]
    imported = {alias.name.split(".")[0] for node in imports for alias in node.names}
    assert "torch" not in imported
    assert "requests" not in imported
    assert not any(isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.startswith("http://") for node in ast.walk(tree))


def test_e4_cohort_and_raw_population_integrity():
    cohort = jsonl(E43 / "E4_3_COHORT_AND_STRATA_MANIFEST.jsonl")
    raw = jsonl(E43 / "E4_3_RAW_NATIVE_INFERENCE.jsonl")
    assert len(cohort) == 380
    assert sum(row["cohort"] == "representative" for row in cohort) == 300
    assert sum(row["cohort"] == "diagnostic" for row in cohort) == 80
    assert len({row["query_id"] for row in cohort}) == 380
    full_cohort_valid = [row for row in raw if row.get("status") == "VALID" and row.get("query_id") in {x["query_id"] for x in cohort}]
    assert len(full_cohort_valid) == 4560
    assert sum(row.get("status") == "VALID" for row in raw) == 4620


def test_recheck_outputs_have_explicit_denominators():
    path = OUT / "E4_R_E4_3_SCORECARD_RECHECK.csv"
    if not path.is_file():
        pytest.skip("E4-R outputs are generated by the execution script")
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    assert len(rows) == 24
    assert {int(row["k"]) for row in rows} == {10, 20}
    assert {row["cohort"] for row in rows} == {"representative", "diagnostic"}
    for row in rows:
        assert row["cssr_u_den"] == row["valid_n"]
        assert row["cssr_c_den"] != ""
        assert row["complete_support_den"] in {"300", "80"}


def test_confirmatory_lock_and_manifest_if_finalized():
    gate = OUT / "E4_R_OWNER_REVIEW_GATE.md"
    manifest = OUT / "E4_R_PROVENANCE_MANIFEST.json"
    if not gate.is_file() or not manifest.is_file():
        pytest.skip("final owner gate is created after the audit test phase")
    value = json.loads(manifest.read_text(encoding="utf-8"))
    if value.get("status") != "E4_R_OWNER_REVIEW_READY":
        pytest.skip("owner manifest is refreshed after the audit test phase")
    assert "E4-5" in gate.read_text(encoding="utf-8")
    assert value["scientific_status"] == "CONFIRMATORY_DATA_NOT_READY"
    assert value["jev_calls"] == 0
    assert value["paid_api_calls"] == 0
    assert value["holdout_accessed"] is False
    for rel in value["files"]:
        path = ROOT / rel
        assert path.is_file(), rel
